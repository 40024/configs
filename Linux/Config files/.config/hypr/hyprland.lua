-- Hyprland 0.57+ Lua configuration entry point.
-- Keep each area in its own module, similar to the old sourced .conf files.
-- Hyprland-only legacy files were removed; remaining .conf files serve Hyprlock,
-- Hypridle, HyDE selectors, or theme data consumed by the Lua modules.
-- Hyprland loads this file at startup and watches it for configuration changes.
-- Keep this entry point updated after edits to included modules to apply them.
-- HyDE script shortcuts use ~/.local/lib/hyde (the core's $scrPath).
-- The Steam-aware close binding is implemented in Lua (no legacy hyprctl dispatch).
-- HyDE's runtime environment and keybind-hint data are generated by hyde.lua.
-- Selected theme, animation and workflow profiles are read by their Lua modules.
-- Theme parsing handles nested legacy theme sections without sourcing hyprlang.
-- Theme boolean values are normalized before setting Lua config options.
-- Workflow presets and animation profiles remain selectable from their old HyDE selectors.

require("hyde")          -- HyDE core environment, defaults and startup
require("nvidia")        -- NVIDIA-specific environment and cursor settings
require("appearance")    -- active Tokyo Night theme and animation settings
require("animations")    -- selected HyDE animation profile, translated to Lua
require("monitors")      -- generated monitor layout
require("keybindings")   -- keyboard shortcuts
require("windowrules")   -- window and layer rules
require("userprefs")     -- personal input settings and autostart
require("workflows")     -- workflow overrides (loaded last, as before)
